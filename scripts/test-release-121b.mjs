import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
import {purchaseNeeds} from '../src/logic.js';
const data={inventory:[{id:'chain /1',name:'Kette',manufacturer:'Shimano',quantity:0,minStock:1,unit:'Stück'}],shopping:[]};
const context=vm.createContext({data,purchaseNeeds,URL,Intl,encodeURIComponent,esc:v=>String(v??'').replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;'),empty:()=>'',bike24Link:()=> 'https://example.test'});
vm.runInContext(await readFile(new URL('../src/supplies.js',import.meta.url),'utf8'),context);
const render=()=>vm.runInContext('purchasingTile()',context);
assert.match(render(),/href="#stock\/chain%20%2F1">Shimano Kette<\/a>/);
assert.match(render(),/data-action="restock"/);
data.shopping=[{id:'p',inventoryId:'chain /1',name:'Ersatzkette',manufacturer:'SRAM',source:'online',status:'needed',quantity:1,usedQuantity:0,unit:'Stück'}];
assert.match(render(),/href="#stock\/chain%20%2F1">SRAM Ersatzkette<\/a>/);
assert.match(render(),/data-action="purchase-edit"/);
data.shopping[0].inventoryId='missing';
assert.match(render(),/<strong>SRAM Ersatzkette<\/strong>/);
assert.doesNotMatch(render(),/#stock\/missing/);
data.inventory=[];data.shopping[0].manufacturer='';
assert.match(render(),/<strong>Ersatzkette<\/strong>/);
data.shopping[0].manufacturer='<script>';
assert.doesNotMatch(render(),/<script>/);
console.log('PASS: dashboard stock links, manufacturer-first titles, missing-stock fallback, escaped labels and purchase/restock actions.');
